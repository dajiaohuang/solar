test('touch tap focuses a body and a touch drag does not select it', async ({ page }, info) => {
  test.skip(!info.project.use.hasTouch, 'Touch-device interaction')
  await page.goto('./?v=4&view=2d&lang=en')
  await expect(page.getByTestId('ephemeris-status').locator(':scope > summary')).not.toContainText('Loading')
  const label = page.locator('.placed-floating-label[data-body-id="mercury"]')
  await expect(label).toBeVisible()
  const name = (await label.innerText()).trim()
  const readPoint = () => label.evaluate(node => {
    const element = node as HTMLElement, bounds = node.closest('.viz-canvas')!.getBoundingClientRect()
    return { x: bounds.left + Number(element.dataset.anchorX), y: bounds.top + Number(element.dataset.anchorY) }
  })
  const point = await readPoint()
  const previous = await page.locator('.inspector-toggle strong').innerText()
  const client = await page.context().newCDPSession(page)
  await client.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [point] })
  await client.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: point.x + 50, y: point.y }] })
  await client.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [point] })
  await client.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await expect(page.locator('.inspector-toggle strong')).toHaveText(previous)
  await page.waitForTimeout(500)
  const currentPoint = await readPoint()
  await page.screenshot({ path: info.outputPath('touch-before-tap.png') })
  await page.touchscreen.tap(currentPoint.x, currentPoint.y)
  await expect(page.locator('.inspector-toggle strong')).toHaveText(name)
  await client.detach()
})

test('3D drag returning to its start does not focus a body, while a fresh click does', async ({ page }) => {
  await page.goto('./?v=4&view=3d&lang=en')
  const scene = page.getByTestId('trajectory-canvas-3d')
  await expect(scene).toBeVisible()
  await expect(page.getByTestId('ephemeris-status').locator(':scope > summary')).not.toContainText('Loading')
  const bounds = (await scene.boundingBox())!
  const point = { x: bounds.x + bounds.width / 2, y: bounds.y + bounds.height / 2 }
  const focus = page.locator('.inspector-toggle strong'), before = await focus.innerText()
  await page.mouse.move(point.x, point.y); await page.mouse.down()
  await page.mouse.move(point.x + 40, point.y, { steps: 4 }); await page.mouse.move(point.x, point.y); await page.mouse.up()
  await expect(focus).toHaveText(before)
  await page.mouse.click(point.x, point.y)
  await expect(focus).not.toHaveText(before)
})

test('hover stays within the viewport and clears when seeking or switching views', async ({ page }) => {
  await page.goto('./?v=4&view=2d&lang=en&bodies=mercury&ref=sun&speed=0')
  await expect(page.getByTestId('ephemeris-status').locator(':scope > summary')).toContainText('1/1')
  const label = page.locator('.placed-floating-label[data-body-id="mercury"]')
  await expect(label).toBeVisible()
  const markerPoint = () => label.evaluate(node => {
    const element = node as HTMLElement, bounds = node.closest('.viz-canvas')!.getBoundingClientRect()
    return { x: bounds.left + Number(element.dataset.anchorX), y: bounds.top + Number(element.dataset.anchorY) }
  })
  const point = await markerPoint()
  await page.mouse.move(point.x, point.y)
  const tooltip = page.locator('.atlas-tooltip')
  await expect(tooltip).toContainText('Mercury')
  const box = (await tooltip.boundingBox())!, viewport = page.viewportSize()!
  expect(box.x).toBeGreaterThanOrEqual(8); expect(box.y).toBeGreaterThanOrEqual(8)
  expect(box.x + box.width).toBeLessThanOrEqual(viewport.width - 8)
  expect(box.y + box.height).toBeLessThanOrEqual(viewport.height - 8)
  await page.locator('.simulation-bar input[type=date]').fill('2027-01-02')
  await page.locator('.simulation-bar input[type=date]').press('Tab')
  await expect(tooltip).toHaveCount(0)
  const nextPoint = await markerPoint()
  await page.mouse.move(nextPoint.x + 20, nextPoint.y); await page.mouse.move(nextPoint.x, nextPoint.y)
  await expect(tooltip).toBeVisible()
  await page.locator('.simulation-bar').getByRole('button', { name: '3D', exact: true }).click()
  await expect(tooltip).toHaveCount(0)
})
