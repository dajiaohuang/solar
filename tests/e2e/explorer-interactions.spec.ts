test('2D focuses a clicked body, suppresses drag clicks and recovers after outside release', async ({ page }) => {
  await page.goto('./?v=4&view=2d&lang=en')
  const canvas = page.locator('canvas.trajectory-canvas')
  await expect(canvas).toBeVisible()
  await expect(page.getByTestId('ephemeris-status').locator(':scope > summary')).not.toContainText('Loading')
  const label = page.locator('.placed-floating-label[data-body-id="mercury"]')
  await expect(label).toBeVisible()
  const name = (await label.innerText()).trim()
  const readPoint = () => label.evaluate(node => {
    const element = node as HTMLElement, bounds = node.closest('.viz-canvas')!.getBoundingClientRect()
    return { x: bounds.left + Number(element.dataset.anchorX), y: bounds.top + Number(element.dataset.anchorY) }
  })
  const point = await readPoint()
  const focus = page.locator('.inspector-toggle strong'), previous = await focus.innerText()
  await page.mouse.move(point.x, point.y); await page.mouse.down()
  await page.mouse.move(point.x + 40, point.y, { steps: 4 }); await page.mouse.move(point.x, point.y); await page.mouse.up()
  await expect(focus).toHaveText(previous)
  await page.mouse.move(point.x, point.y); await page.mouse.down(); await page.mouse.move(0, 0); await page.mouse.up()
  await page.waitForTimeout(500)
  const currentPoint = await readPoint()
  await page.mouse.click(currentPoint.x, currentPoint.y)
  await expect(focus).toHaveText(name)
  await page.locator('.inspector-toggle').click()
  await expect(page.locator('.inspector-header h2')).toHaveText(name)
})

test('view switches preserve planar settings and disclose the active mode', async ({ page }) => {
  await page.goto('./?v=4&view=2d&lang=en')
  await page.locator('.advanced-controls > summary').click()
  const offset = page.locator('.view-offset-grid input').first()
  await offset.fill('-2.5')
  const orbits = page.getByRole('checkbox', { name: 'Osculating orbit ellipses', exact: true })
  await orbits.check()
  const modes = page.locator('.simulation-bar .segmented-control')
  await modes.getByRole('button', { name: '3D', exact: true }).click()
  await expect(modes.getByRole('button', { name: '3D', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(offset).toBeDisabled()
  await expect(page.getByRole('checkbox', { name: /Osculating orbit ellipses · 2D only/ })).not.toBeChecked()
  await modes.getByRole('button', { name: '2D', exact: true }).click()
  await expect(offset).toHaveValue('-2.5')
  await expect(orbits).toBeChecked()
  await expect(modes.getByRole('button', { name: '2D', exact: true })).toHaveAttribute('aria-pressed', 'true')
})

test('empty numeric drafts do not reset offsets or catalog ranges to zero', async ({ page }) => {
  await page.goto('./?v=4&view=2d&lang=en')
  await page.locator('.advanced-controls > summary').click()
  const offset = page.locator('.view-offset-grid input').first()
  await offset.fill('-2.5'); await offset.fill('')
  await expect(offset).toHaveValue('')
  await offset.press('Tab'); await expect(offset).toHaveValue('-2.5')
  await offset.fill(''); await offset.pressSequentially('-1.25')
  await expect(offset).toHaveValue('-1.25')
  await offset.press('Tab'); await expect(offset).toHaveValue('-1.25')
  await page.goto('./?v=4&page=catalog&lang=en')
  const minimum = page.getByRole('spinbutton', { name: 'a (AU): Minimum', exact: true })
  await minimum.fill('3'); await minimum.fill(''); await minimum.press('Tab')
  await expect(minimum).toHaveValue('3')
})

